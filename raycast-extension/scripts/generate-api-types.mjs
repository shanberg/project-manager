#!/usr/bin/env node
/**
 * Generate the typed client's inputs from `pm api describe`.
 *
 * The manifest is the contract's own description of itself, so the types here are derived from it
 * rather than written beside it — which is the difference between a client that can drift from the
 * binary and one that can't. Run `npm run generate-api` after changing an action; `npm test` fails if
 * the checked-in file no longer matches what the installed `pm` describes.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT = path.join(here, "..", "src", "lib", "pm-api.generated.ts");

export function pmBinary() {
  return process.env.PM_CLI_PATH || "pm";
}

export function describe(binary = pmBinary()) {
  return JSON.parse(execFileSync(binary, ["api", "describe"], { encoding: "utf-8" }));
}

/** `task.setDue` -> `TaskSetDueInput`. */
function interfaceName(action) {
  return (
    action
      .split(".")
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join("") + "Input"
  );
}

/** One property's TypeScript type, from its published schema. */
function typeOf(schema) {
  if (Array.isArray(schema.enum)) {
    return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  }
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "object":
      // The only object in the contract is a task reference, and it has a name here already.
      return schema.properties?.digest ? "TaskRef" : "Record<string, unknown>";
    default:
      // A field the schema deliberately leaves open — `value`, whose shape depends on the key.
      return "JsonValue";
  }
}

function comment(text, indent = "  ") {
  return `${indent}/** ${text.replace(/\*\//g, "*\\/")} */`;
}

export function render(manifest) {
  const lines = [
    "// Generated by scripts/generate-api-types.mjs from `pm api describe`. Do not edit by hand.",
    "//",
    "// Every action the pm contract publishes, as an input type. Regenerate with `npm run generate-api`",
    "// after changing an action; the test in __tests__/pm-api.generated.test.ts fails when this file",
    "// and the installed binary disagree.",
    "",
    'import type { JsonValue, TaskRef } from "./pm-api";',
    "",
    `export const API_CONTRACT_VERSION = ${JSON.stringify(manifest.contractVersion)};`,
    "",
  ];

  const actions = [...manifest.actions].sort((a, b) => a.name.localeCompare(b.name));

  for (const action of actions) {
    const properties = action.input.properties ?? {};
    const required = new Set(action.input.required ?? []);
    lines.push(comment(action.summary, ""));
    const keys = Object.keys(properties).sort();
    if (keys.length === 0) {
      // An action that takes nothing. A type alias rather than an empty interface, which eslint
      // rejects because `interface X {}` accepts any non-nullish value, `0` and `""` included.
      lines.push(`export type ${interfaceName(action.name)} = Record<string, never>;`, "");
      continue;
    }
    lines.push(`export interface ${interfaceName(action.name)} {`);
    for (const key of keys) {
      const schema = properties[key];
      if (schema.description) lines.push(comment(schema.description));
      lines.push(`  ${key}${required.has(key) ? "" : "?"}: ${typeOf(schema)};`);
    }
    lines.push("}", "");
  }

  lines.push("/** Every action, mapped to the input it takes. */");
  lines.push("export interface ApiInputs {");
  for (const action of actions) {
    lines.push(`  ${JSON.stringify(action.name)}: ${interfaceName(action.name)};`);
  }
  lines.push("}", "");

  lines.push("export type ApiActionName = keyof ApiInputs;");
  lines.push("");
  lines.push("/** Which tier each action belongs to, so a caller can tell a read from a write. */");
  // Wrapped the way Prettier wants it, so the generated file passes the same lint as the rest.
  lines.push("export const API_TIERS: Record<");
  lines.push("  ApiActionName,");
  lines.push('  "mutation" | "query" | "affordance"');
  lines.push("> = {");
  for (const action of actions) {
    lines.push(`  ${JSON.stringify(action.name)}: ${JSON.stringify(action.tier)},`);
  }
  lines.push("};", "");
  return lines.join("\n");
}

function main() {
  const manifest = describe();
  const rendered = render(manifest);
  // `--print` writes nothing and emits what it would have written, so a test can compare without
  // importing this module across the TypeScript boundary.
  if (process.argv.includes("--print")) {
    process.stdout.write(rendered);
    return;
  }
  const unchanged = existsSync(OUTPUT) && readFileSync(OUTPUT, "utf-8") === rendered;
  writeFileSync(OUTPUT, rendered);
  const count = manifest.actions.length;
  console.log(
    `${unchanged ? "unchanged" : "wrote"} ${path.relative(process.cwd(), OUTPUT)} — ` +
      `${count} actions, contract ${manifest.contractVersion}`,
  );
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) main();
