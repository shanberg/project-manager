#!/usr/bin/env node
/**
 * Generate the Mac app's action names from `pm api describe`.
 *
 * The sibling of `raycast-extension/scripts/generate-api-types.mjs`, and it exists for the same
 * reason that one does — derived from the manifest rather than written beside it, so the app cannot
 * drift from the binary it links.
 *
 * It also exists because the safety was inverted. Raycast talks to the contract over JSON and gets
 * compile-time checking; the Mac app links PmLib, calls the dispatcher in-process, is the heaviest
 * caller in the tree, and passed **raw strings**. `PMContract.perform("task.setDeu", …)` compiled
 * happily and threw at runtime, in a build the extension would have rejected.
 *
 * Run `node pm-mac/scripts/generate-api-actions.mjs` after changing an action. `PMActionsTests`
 * fails when the checked-in file and the binary disagree.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT = path.join(here, "..", "PM", "Model", "PMActions.generated.swift");

/**
 * Which `pm` to describe: the one asked for, else the one built from this repo, else whatever is
 * installed. Same order and the same reasoning as the Raycast generator — the drift check is about
 * *this tree*, so a stale globally-installed binary must not be what it compares against.
 */
export function pmBinary() {
  if (process.env.PM_CLI_PATH) return process.env.PM_CLI_PATH;
  for (const build of ["debug", "release"]) {
    const built = path.join(here, "..", "..", "pm-swift", ".build", build, "pm");
    if (existsSync(built)) return built;
  }
  return "pm";
}

export function describe(binary = pmBinary()) {
  return JSON.parse(execFileSync(binary, ["api", "describe"], { encoding: "utf-8" }));
}

/** `task.setDue` -> `taskSetDue`, which is how a Swift case is spelled. */
function caseName(action) {
  const [group, ...rest] = action.split(".");
  return group + rest.map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join("");
}

/** The fields an action will not run without, as the manifest's own `required` list. */
function requiredFields(action) {
  return [...(action.input.required ?? [])].sort();
}

/**
 * Groups of fields of which exactly one must be given — `task` or `tasks`, `due` or `clearDue`.
 * Published as `allOf: [{ oneOf: [{required: [...]}, …] }]`, which is JSON Schema's way of saying it.
 */
function exclusiveGroups(action) {
  const all = action.input.allOf ?? [];
  return all
    .map((clause) => (clause.oneOf ?? []).map((branch) => (branch.required ?? [])[0]).filter(Boolean))
    .filter((group) => group.length > 1);
}

function swiftStringArray(values) {
  return `[${values.map((v) => JSON.stringify(v)).join(", ")}]`;
}

export function render(manifest) {
  const actions = [...manifest.actions].sort((a, b) => a.name.localeCompare(b.name));
  const lines = [
    "// Generated by pm-mac/scripts/generate-api-actions.mjs from `pm api describe`. Do not edit by hand.",
    "//",
    "// Every action the pm contract publishes, as a case. Regenerate with",
    "//     node pm-mac/scripts/generate-api-actions.mjs",
    "// after changing an action; PMActionsTests fails when this file and the binary disagree.",
    "",
    "import PmLib",
    "",
    `/// The contract version this file was generated from.`,
    `///`,
    `/// Named distinctly from PmLib's own \`apiContractVersion\`, which is in scope here — a file-scope`,
    `/// \`let\` of the same name would shadow it silently, and a check comparing the two would then be`,
    `/// comparing a thing with itself.`,
    `let generatedFromContractVersion = ${JSON.stringify(manifest.contractVersion)}`,
    "",
    "/// Every action the contract publishes.",
    "///",
    "/// The point of the enum is that `PMContract.perform(.taskSetDue, …)` cannot be misspelled, where",
    "/// `PMContract.perform(\"task.setDeu\", …)` compiled and threw at runtime. The raw value is the wire",
    "/// name, so nothing has to be translated at the boundary.",
    "enum PMAction: String, CaseIterable, Sendable {",
  ];

  for (const action of actions) {
    lines.push(`    /// ${action.summary}`);
    lines.push(`    case ${caseName(action.name)} = ${JSON.stringify(action.name)}`);
  }

  lines.push("");
  lines.push("    /// Which tier this belongs to, so a caller can tell a read from a write — and so the");
  lines.push("    /// in-process adapter can refuse to send an affordance to the dispatcher.");
  lines.push("    var tier: ApiTier {");
  lines.push("        switch self {");
  for (const tier of ["mutation", "query", "affordance"]) {
    const named = actions.filter((a) => a.tier === tier).map((a) => `.${caseName(a.name)}`);
    if (named.length === 0) continue;
    lines.push(`        case ${named.join(", ")}:`);
    lines.push(`            return .${tier}`);
  }
  lines.push("        }");
  lines.push("    }");
  lines.push("");
  lines.push("    /// The fields this action will not run without.");
  lines.push("    ///");
  lines.push("    /// `ApiInput` is one struct of twenty-nine optional fields serving every action, so a");
  lines.push("    /// caller that forgets one is only told when the dispatcher refuses it. Published here so");
  lines.push("    /// a debug build can say so at the call site instead — see `PMContract.perform`.");
  lines.push("    var requiredFields: [String] {");
  lines.push("        switch self {");
  const byRequired = new Map();
  for (const action of actions) {
    const key = swiftStringArray(requiredFields(action));
    if (!byRequired.has(key)) byRequired.set(key, []);
    byRequired.get(key).push(`.${caseName(action.name)}`);
  }
  for (const [fields, names] of byRequired) {
    lines.push(`        case ${names.join(", ")}:`);
    lines.push(`            return ${fields}`);
  }
  lines.push("        }");
  lines.push("    }");
  lines.push("");
  lines.push("    /// Groups of fields of which exactly one must be given — `task` or `tasks` for the actions");
  lines.push("    /// that take either, `due` or `clearDue` for the one that both sets and clears.");
  lines.push("    var exclusiveGroups: [[String]] {");
  lines.push("        switch self {");
  const byExclusive = new Map();
  for (const action of actions) {
    const groups = exclusiveGroups(action);
    const key = `[${groups.map(swiftStringArray).join(", ")}]`;
    if (!byExclusive.has(key)) byExclusive.set(key, []);
    byExclusive.get(key).push(`.${caseName(action.name)}`);
  }
  for (const [groups, names] of byExclusive) {
    lines.push(`        case ${names.join(", ")}:`);
    lines.push(`            return ${groups}`);
  }
  lines.push("        }");
  lines.push("    }");
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

function main() {
  const manifest = describe();
  const rendered = render(manifest);
  // `--print` writes nothing and emits what it would have written, so the drift test can compare
  // without re-implementing any of this.
  if (process.argv.includes("--print")) {
    process.stdout.write(rendered);
    return;
  }
  const unchanged = existsSync(OUTPUT) && readFileSync(OUTPUT, "utf-8") === rendered;
  writeFileSync(OUTPUT, rendered);
  console.log(
    `${unchanged ? "unchanged" : "wrote"} ${path.relative(process.cwd(), OUTPUT)} — ` +
      `${manifest.actions.length} actions, contract ${manifest.contractVersion}`,
  );
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) main();
